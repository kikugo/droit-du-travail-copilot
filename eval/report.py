"""Write the README results tables from results/*.json (never typed by hand).

    uv run python -m eval.report

Replaces everything between <!-- RESULTS:START --> and <!-- RESULTS:END --> in README.md.
Running it twice on the same results gives the same README.
"""

import json
import math
import re
from pathlib import Path

README = Path("README.md")
RESULTS = Path("results")
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
INDEX_LABELS = {"free": "Free tier, trimmed corpus", "basic": "Basic tier, full corpus"}
MODE_LABELS = {
    "keyword": "BM25 (keyword)",
    "vector": "Vector",
    "hybrid": "Hybrid (RRF)",
    "hybrid_semantic": "Hybrid + semantic ranker",
}


def pct(x) -> str:
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x * 100:.0f}%"


def ci(pair) -> str:
    if not pair or any(v is None or math.isnan(v) for v in pair):
        return ""
    return f" ({pair[0] * 100:.0f}–{pair[1] * 100:.0f})"


def retrieval_table(data: dict) -> str:
    lines = [
        (
            f"**Retrieval, {INDEX_LABELS.get(data['label'], data['label'])}** "
            f"({data['n_questions']} answerable questions, top {10}, 95% CI on hit@5)"
        ),
        "",
        "| Mode | hit@1 | hit@3 | hit@5 | MRR@10 | recall@5 | p95 |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in data["modes"]:
        label = MODE_LABELS.get(m["mode"], m["mode"])
        if not m["available"]:
            lines.append(f"| {label} | not available on this tier ({m['error']}) ||||||")
            continue
        t = m["totals"]
        lines.append(
            f"| {label} | {pct(t['hit@1'])} | {pct(t['hit@3'])} | {pct(t['hit@5'])}{ci(t['hit@5_ci'])}"
            f" | {t['mrr@10']:.2f} | {pct(t['recall@5'])} | {t['p95_ms']:.0f} ms |"
        )
    return "\n".join(lines)


def agent_table(data: dict) -> str:
    s = data["summary"]
    judge = s.get("judge", {}).get("model", "the judge")
    rows = [
        (
            "Citation accuracy (every cited article is gold)",
            pct(s["citation_accuracy"]) + ci(s["citation_accuracy_ci"]),
        ),
        ("At least one gold article cited (answerable)", pct(s["citation_hit"])),
        (
            f"Faithfulness ({judge}, n={s['faithfulness_n']})",
            pct(s["faithfulness"]) + ci(s["faithfulness_ci"]),
        ),
        ("Refusal accuracy (out-of-scope questions)", pct(s["refusal_accuracy"])),
        ("False refusals (answerable questions)", pct(s["false_refusal_rate"])),
        ("Calculator correctness", pct(s["calculator_correctness"])),
        ("Answers citing an article no tool returned", pct(s["unsupported_citation_rate"])),
        ("Latency p50 / p95", f"{s['p50_s']:.1f} s / {s['p95_s']:.1f} s"),
        ("Tokens per query", f"{s['tokens_per_query']:.0f}"),
        ("Model cost per 1,000 queries", f"${s['usd_per_1000_queries']:.2f}"),
    ]
    lines = [
        (
            f"**Agent answers** ({s['n']} questions, {data['config']['chat']}, prices checked "
            f"{data['prices_checked']}, 95% CI in brackets)"
        ),
        "",
        "| Metric | Value |",
        "|---|---|",
        *[f"| {name} | {value} |" for name, value in rows],
    ]
    by_type: dict[str, list] = {}
    for r in data["results"]:
        by_type.setdefault(r["type"], []).append(r["scores"]["citation_accuracy"])
    lines += ["", "| Question type | n | Citation accuracy |", "|---|---|---|"]
    for t, vals in by_type.items():
        lines.append(f"| {t} | {len(vals)} | {pct(sum(vals) / len(vals))} |")
    return "\n".join(lines)


def build(results_dir: Path = RESULTS) -> str:
    parts = []
    for label in ("free", "basic"):
        path = results_dir / f"retrieval_{label}.json"
        if path.exists():
            parts.append(retrieval_table(json.loads(path.read_text(encoding="utf-8"))))
    agent = results_dir / "agent_eval.json"
    if agent.exists():
        parts.append(agent_table(json.loads(agent.read_text(encoding="utf-8"))))
    note = "_Generated by `make report` from `results/*.json`._"
    return "\n\n".join([note, *parts]) if parts else note


def write(readme: Path = README, results_dir: Path = RESULTS) -> None:
    text = readme.read_text(encoding="utf-8")
    block = f"{START}\n{build(results_dir)}\n{END}"
    if START in text and END in text:
        text = re.sub(
            re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.DOTALL
        )
    else:
        text = text.rstrip() + f"\n\n## Results\n\n{block}\n"
    readme.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    write()
    print(f"updated {README}")
